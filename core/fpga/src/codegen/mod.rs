//! Source generation: one [`BlockSpec`] -> Verilog-2001, SystemVerilog or
//! Rust with the same pins ([`crate::signals`]) and the same clock-edge
//! semantics ([`crate::core`]).
//!
//! ```text
//!  generate(spec, Language::Verilog)       -> <name>.v
//!  generate(spec, Language::SystemVerilog) -> <name>.sv
//!  generate(spec, Language::Rust)          -> <name>.rs  (impl FpgaCore)
//! ```
//!
//! Each project keeps its sources in `core/fpga/hdl/<name>/` (spec, .v, .sv,
//! .rs); the bundled example's outputs there are checked: a test fails
//! when they drift from the generator, and another runs the generated Rust
//! against [`crate::SpecCore`] in lockstep.

mod hdl;
pub mod rust;

use crate::spec::{Access, BlockSpec, Register};

/// A target language.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Language {
    Verilog,
    SystemVerilog,
    Rust,
}

impl Language {
    pub const ALL: [Self; 3] = [Self::Verilog, Self::SystemVerilog, Self::Rust];

    pub const fn extension(self) -> &'static str {
        match self {
            Self::Verilog => "v",
            Self::SystemVerilog => "sv",
            Self::Rust => "rs",
        }
    }

    pub const fn label(self) -> &'static str {
        match self {
            Self::Verilog => "Verilog",
            Self::SystemVerilog => "SystemVerilog",
            Self::Rust => "Rust",
        }
    }
}

/// Source of `spec` in `language`. `spec` must be valid.
pub fn generate(spec: &BlockSpec, language: Language) -> String {
    match language {
        Language::Verilog => hdl::generate(spec, false),
        Language::SystemVerilog => hdl::generate(spec, true),
        Language::Rust => rust::generate(spec),
    }
}

/// Writes all three sources of `spec` into `dir` as `<name>.<ext>`.
///
/// # Errors
/// File system errors.
pub fn write_all(
    spec: &BlockSpec,
    dir: &std::path::Path,
) -> std::io::Result<Vec<std::path::PathBuf>> {
    std::fs::create_dir_all(dir)?;
    Language::ALL
        .iter()
        .map(|&lang| {
            let path = dir.join(format!("{}.{}", spec.name, lang.extension()));
            std::fs::write(&path, generate(spec, lang))?;
            Ok(path)
        })
        .collect()
}

/// `fpga_timer` -> `FpgaTimer`.
pub fn camel_case(name: &str) -> String {
    name.split('_')
        .map(|part| {
            let mut chars = part.chars();
            chars.next().map_or_else(String::new, |c| {
                let mut word = c.to_ascii_uppercase().to_string();
                word.push_str(chars.as_str());
                word
            })
        })
        .collect()
}

fn header(spec: &BlockSpec, comment: &str) -> String {
    let mut out = format!(
        "{comment} Generated by ds_fpga from the `{}` block spec -- regenerate instead of editing.\n",
        spec.name
    );
    if !spec.description.is_empty() {
        out += &format!("{comment} {}\n", spec.description);
    }
    out += &format!(
        "{comment} Pins: core/fpga/src/signals.rs. Clock-edge semantics: core/fpga/src/core.rs.\n"
    );
    out += &format!(
        "{comment} CPU window: 0x{:08X}..0x{:08X}, FPGA clock: 33.51 MHz / {}.\n",
        ds_emu::slot2::SLOT2_START + spec.base,
        ds_emu::slot2::SLOT2_START + spec.base + spec.size,
        spec.clock_div
    );
    out
}

/// Register-map comment lines shared by all three languages.
fn register_map(spec: &BlockSpec, comment: &str) -> String {
    spec.registers
        .iter()
        .map(|r| {
            format!(
                "{comment}   +0x{:04X} {:<12} {:<8} reset 0x{:08X}  {}\n",
                r.offset,
                r.name,
                access_label(&r.access),
                r.reset,
                r.description
            )
        })
        .collect()
}

pub const fn access_label(access: &Access) -> &'static str {
    match access {
        Access::Rw => "rw",
        Access::Const => "const",
        Access::Counter { .. } => "counter",
        Access::W1c { .. } => "w1c",
    }
}

/// Registers that hold state (everything but constants).
fn stateful(spec: &BlockSpec) -> impl Iterator<Item = &Register> {
    spec.registers.iter().filter(|r| !matches!(r.access, Access::Const))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn bundled(lang: Language) -> &'static str {
        match lang {
            Language::Verilog => include_str!("../../hdl/fpga_timer/fpga_timer.v"),
            Language::SystemVerilog => include_str!("../../hdl/fpga_timer/fpga_timer.sv"),
            Language::Rust => include_str!("../../hdl/fpga_timer/fpga_timer.rs"),
        }
    }

    /// Run `cargo test -p ds_fpga -- --ignored regenerate` after changing a
    /// generator or the example spec.
    #[test]
    #[ignore = "writes core/fpga/hdl"]
    fn regenerate() {
        let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("hdl").join("fpga_timer");
        assert!(write_all(&crate::example_timer(), &dir).is_ok());
    }

    #[test]
    fn bundled_sources_are_up_to_date() {
        let spec = crate::example_timer();
        for lang in Language::ALL {
            assert_eq!(
                generate(&spec, lang).replace("\r\n", "\n"),
                bundled(lang).replace("\r\n", "\n"),
                "hdl/fpga_timer/fpga_timer.{} is stale: run the `regenerate` test",
                lang.extension()
            );
        }
    }

    #[test]
    fn camel_case_names() {
        assert_eq!(camel_case("fpga_timer"), "FpgaTimer");
        assert_eq!(camel_case("dsp2"), "Dsp2");
    }
}
